"""Patch the generated Android project after `cap add android`.

The android/ project is generated by `cap add android` (locally and in CI)
and is not committed, so everything the generated project needs beyond
Capacitor's defaults is reapplied here after every generation:

1. AndroidManifest.xml: the extra permissions Larixy needs.
2. Firebase / FCM: the committed google-services.json is copied into
   android/app/, and the Google Services Gradle plugin is made sure to
   be applied. The Capacitor template already applies it conditionally
   when the JSON is present (and the root build.gradle already carries
   its classpath), so on the current template this step is just the
   copy; the explicit fallbacks only fire if a future template drops
   that wiring.
3. Release signing: when the ANDROID_KEYSTORE_* environment variables
   are set (the release CI job), a signingConfigs.release block that
   reads them via System.getenv is injected into android/app/build.gradle
   and wired into buildTypes.release. No secret value is ever written
   to a file. When the variables are absent (debug builds, local runs)
   the generated project is left untouched.

Run after `cap add android`:

    python3 scripts/patch-android-manifest.py

Idempotent: re-running it changes nothing that is already in place.
"""

import os
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ANDROID_DIR = ROOT / "android"
MANIFEST = ANDROID_DIR / "app" / "src" / "main" / "AndroidManifest.xml"
APP_BUILD_GRADLE = ANDROID_DIR / "app" / "build.gradle"
ROOT_BUILD_GRADLE = ANDROID_DIR / "build.gradle"
GOOGLE_SERVICES_SOURCE = ROOT / "google-services.json"
GOOGLE_SERVICES_DEST = ANDROID_DIR / "app" / "google-services.json"

PERMISSIONS = [
    # Voice channels: microphone capture and audio routing.
    "android.permission.RECORD_AUDIO",
    "android.permission.MODIFY_AUDIO_SETTINGS",
    # Video calls.
    "android.permission.CAMERA",
    # Push notifications (Android 13+ runtime permission).
    "android.permission.POST_NOTIFICATIONS",
]

GOOGLE_SERVICES_PLUGIN = "com.google.gms.google-services"
GOOGLE_SERVICES_CLASSPATH = "com.google.gms:google-services:4.4.2"

SIGNING_ENV_VARS = [
    "ANDROID_KEYSTORE_PATH",
    "ANDROID_KEYSTORE_PASSWORD",
    "ANDROID_KEY_ALIAS",
    "ANDROID_KEY_PASSWORD",
]
SIGNING_MARKER = "larixy:release-signing"


def patch_manifest() -> int:
    if not MANIFEST.exists():
        print(f"manifest not found: {MANIFEST} (run `cap add android` first)", file=sys.stderr)
        return 1
    text = MANIFEST.read_text(encoding="utf-8")
    missing = [p for p in PERMISSIONS if f'android:name="{p}"' not in text]
    if not missing:
        print("manifest: all permissions already present")
        return 0
    block = "".join(f'\n    <uses-permission android:name="{p}" />' for p in missing) + "\n"
    match = re.search(r"<manifest\b[^>]*>", text)
    if match is None:
        print("could not find the <manifest> opening tag", file=sys.stderr)
        return 1
    text = text[: match.end()] + block + text[match.end() :]
    MANIFEST.write_text(text, encoding="utf-8")
    print(f"manifest: added {len(missing)} permission(s): {', '.join(missing)}")
    return 0


def patch_google_services() -> None:
    if not GOOGLE_SERVICES_SOURCE.exists():
        print(f"google-services: {GOOGLE_SERVICES_SOURCE} not present, skipping Firebase wiring")
        return
    if GOOGLE_SERVICES_DEST.exists() and GOOGLE_SERVICES_DEST.read_bytes() == GOOGLE_SERVICES_SOURCE.read_bytes():
        print("google-services: android/app/google-services.json already up to date")
    else:
        shutil.copyfile(GOOGLE_SERVICES_SOURCE, GOOGLE_SERVICES_DEST)
        print("google-services: copied google-services.json into android/app/")

    if not APP_BUILD_GRADLE.exists():
        print(f"google-services: {APP_BUILD_GRADLE} not found, skipping plugin check", file=sys.stderr)
        return
    text = APP_BUILD_GRADLE.read_text(encoding="utf-8")
    if GOOGLE_SERVICES_PLUGIN in text:
        # The Capacitor template applies the plugin conditionally on the
        # JSON being present, which the copy above guarantees.
        print("google-services: plugin already declared in android/app/build.gradle")
        return
    # Fallback for a template that drops the conditional application:
    # apply the plugin explicitly and make sure the root buildscript
    # carries its classpath.
    text += (
        "\n// Applied by scripts/patch-android-manifest.py (Firebase/FCM).\n"
        f"apply plugin: '{GOOGLE_SERVICES_PLUGIN}'\n"
    )
    APP_BUILD_GRADLE.write_text(text, encoding="utf-8")
    print("google-services: plugin was not declared; appended apply plugin line")
    if ROOT_BUILD_GRADLE.exists():
        root_text = ROOT_BUILD_GRADLE.read_text(encoding="utf-8")
        if "com.google.gms:google-services" not in root_text:
            match = re.search(r"buildscript\s*\{.*?dependencies\s*\{", root_text, re.DOTALL)
            if match is not None:
                root_text = (
                    root_text[: match.end()]
                    + f"\n        classpath '{GOOGLE_SERVICES_CLASSPATH}'"
                    + root_text[match.end() :]
                )
                ROOT_BUILD_GRADLE.write_text(root_text, encoding="utf-8")
                print("google-services: added plugin classpath to android/build.gradle")
            else:
                print(
                    "google-services: could not find the root buildscript dependencies "
                    "block to add the plugin classpath",
                    file=sys.stderr,
                )


def patch_release_signing() -> None:
    values = {name: os.environ.get(name) for name in SIGNING_ENV_VARS}
    if not any(values.values()):
        print("signing: ANDROID_KEYSTORE_* not set, leaving the generated project unsigned")
        return
    missing = [name for name, value in values.items() if not value]
    if missing:
        print(
            f"signing: incomplete environment (missing: {', '.join(missing)}), "
            "leaving the generated project unsigned",
            file=sys.stderr,
        )
        return
    if not APP_BUILD_GRADLE.exists():
        print(f"signing: {APP_BUILD_GRADLE} not found, skipping", file=sys.stderr)
        return
    text = APP_BUILD_GRADLE.read_text(encoding="utf-8")
    if SIGNING_MARKER in text:
        print("signing: release signingConfig already injected")
        return

    signing_block = (
        f"\n    // {SIGNING_MARKER} — injected by scripts/patch-android-manifest.py.\n"
        "    // Values are read from the environment at build time; no secret is stored here.\n"
        "    signingConfigs {\n"
        "        release {\n"
        '            storeFile file(System.getenv("ANDROID_KEYSTORE_PATH"))\n'
        '            storePassword System.getenv("ANDROID_KEYSTORE_PASSWORD")\n'
        '            keyAlias System.getenv("ANDROID_KEY_ALIAS")\n'
        '            keyPassword System.getenv("ANDROID_KEY_PASSWORD")\n'
        "        }\n"
        "    }\n"
    )
    match = re.search(r"(?m)^android\s*\{\s*$", text)
    if match is None:
        print("signing: could not find the android { block, skipping", file=sys.stderr)
        return
    text = text[: match.end()] + signing_block + text[match.end() :]

    build_types = re.search(r"(buildTypes\s*\{\s*release\s*\{)", text)
    if build_types is not None:
        text = (
            text[: build_types.end()]
            + f"\n            signingConfig signingConfigs.release // {SIGNING_MARKER}"
            + text[build_types.end() :]
        )
    else:
        # The template's release build type was not found in place; wire
        # the signing config through a separate android block instead.
        text += (
            f"\n// {SIGNING_MARKER} — injected by scripts/patch-android-manifest.py.\n"
            "android {\n"
            "    buildTypes {\n"
            "        release {\n"
            "            signingConfig signingConfigs.release\n"
            "        }\n"
            "    }\n"
            "}\n"
        )
    APP_BUILD_GRADLE.write_text(text, encoding="utf-8")
    print("signing: injected signingConfigs.release from the ANDROID_KEYSTORE_* environment")


def main() -> int:
    result = patch_manifest()
    if result != 0:
        return result
    patch_google_services()
    patch_release_signing()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
