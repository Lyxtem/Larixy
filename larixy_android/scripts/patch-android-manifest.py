"""Add the Android permissions Larixy needs to the generated AndroidManifest.xml.

The android/ project is generated by `cap add android` (locally and in CI)
and is not committed, so the extra permissions live here instead of in a
hand-maintained manifest. Run after `cap add android`:

    python3 scripts/patch-android-manifest.py

Idempotent: permissions that are already present are skipped.
"""

import re
import sys
from pathlib import Path

MANIFEST = Path(__file__).resolve().parent.parent / "android" / "app" / "src" / "main" / "AndroidManifest.xml"

PERMISSIONS = [
    # Voice channels: microphone capture and audio routing.
    "android.permission.RECORD_AUDIO",
    "android.permission.MODIFY_AUDIO_SETTINGS",
    # Video calls.
    "android.permission.CAMERA",
    # Push notifications (Android 13+ runtime permission).
    "android.permission.POST_NOTIFICATIONS",
]


def main() -> int:
    if not MANIFEST.exists():
        print(f"manifest not found: {MANIFEST} (run `cap add android` first)", file=sys.stderr)
        return 1
    text = MANIFEST.read_text(encoding="utf-8")
    missing = [p for p in PERMISSIONS if f'android:name="{p}"' not in text]
    if not missing:
        print("all permissions already present")
        return 0
    block = "".join(f'\n    <uses-permission android:name="{p}" />' for p in missing) + "\n"
    match = re.search(r"<manifest\b[^>]*>", text)
    if match is None:
        print("could not find the <manifest> opening tag", file=sys.stderr)
        return 1
    text = text[: match.end()] + block + text[match.end() :]
    MANIFEST.write_text(text, encoding="utf-8")
    print(f"added {len(missing)} permission(s): {', '.join(missing)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
